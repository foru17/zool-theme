#!/usr/bin/env node
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const expectedCommit = 'fe15c16e7463d0c66d6c5730e9d0e832438d98e1'
const expectedLicenseHash = '8f1195d55a2fd315a07d812328470ca9ba2abb78c8d317ff19619d5125e00cea'
const expectedCountryHash = 'f5e99aee5051868b391b9f42e110cb104b7fcd6269807b2dc5e2c80b1e6c9436'
const maximumSourceFlags = 300
const root = fileURLToPath(new URL('../', import.meta.url))
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')

function main() {
  assert.equal(process.argv.length, 3, 'Usage: node scripts/import-flag-icons.mjs /path/to/flag-icons')
  const source = resolve(process.argv[2])
  const commit = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
  assert.equal(commit, expectedCommit, 'flag-icons HEAD must match the pinned v7.3.2 commit')

  const license = readFileSync(join(source, 'LICENSE'))
  const country = readFileSync(join(source, 'country.json'))
  assert.equal(sha256(license), expectedLicenseHash, 'LICENSE SHA256 mismatch')
  assert.equal(sha256(country), expectedCountryHash, 'country.json SHA256 mismatch')

  const entries = JSON.parse(country.toString('utf8'))
  assert.ok(Array.isArray(entries), 'country.json must contain an array')
  const isoEntries = entries.filter((entry) => entry.iso === true)
  assert.ok(isoEntries.length <= maximumSourceFlags, 'ISO entry hard limit exceeded')
  assert.equal(isoEntries.length, 249, 'Expected exactly 249 ISO entries')
  const isoCodes = isoEntries.map((entry) => entry.code)
  assert.ok(isoCodes.every((code) => typeof code === 'string' && /^[a-z]{2}$/.test(code)), 'Expected lowercase two-letter codes')
  assert.equal(new Set(isoCodes).size, isoCodes.length, 'Duplicate ISO codes')

  // Some codes share another code's flag file; see regionFlagCode.
  const codes = isoCodes.filter((code) => code !== 'tw').sort()
  assert.equal(codes.length, 248, 'Expected exactly 248 imported flags')
  assert.ok(codes.includes('cn') && !codes.includes('tw'), 'Imported flag set check failed')

  // Read all source assets before removing any previously generated SVGs.
  const assets = codes.map((code) => {
    const bytes = readFileSync(join(source, 'flags', '4x3', `${code}.svg`))
    assert.ok(bytes.length > 0, `Empty SVG for ${code}`)
    return { code, bytes }
  })
  const manifest = [
    '// generated by scripts/import-flag-icons.mjs; do not edit manually.',
    '// Source: https://github.com/lipis/flag-icons (4:3 SVG flags).',
    '// Some region codes are intentionally absent; see regionFlagCode.',
    'export const FLAG_CODES: ReadonlySet<string> = new Set([',
    ...codes.map((code) => `  '${code}',`),
    '])',
    '',
    'export const FLAG_SOURCE = {',
    "  version: 'v7.3.2',",
    `  commit: '${expectedCommit}',`,
    "  license: 'MIT',",
    '} as const',
    '',
  ].join('\n')

  const destination = join(root, 'public', 'flags')
  mkdirSync(destination, { recursive: true })
  for (const name of readdirSync(destination)) {
    if (name.endsWith('.svg')) unlinkSync(join(destination, name))
  }
  for (const { code, bytes } of assets) {
    writeFileSync(join(destination, `${code}.svg`), bytes)
  }
  writeFileSync(join(destination, 'LICENSE.txt'), license)
  mkdirSync(join(root, 'src', 'core'), { recursive: true })
  writeFileSync(join(root, 'src', 'core', 'flags.manifest.ts'), manifest)

  const generated = readdirSync(destination).filter((name) => name.endsWith('.svg')).sort()
  assert.deepEqual(generated, codes.map((code) => `${code}.svg`), 'Generated flag set mismatch')
  assert.equal(generated.length, 248, 'Expected exactly 248 generated SVGs')
  assert.ok(generated.includes('cn.svg') && !generated.includes('tw.svg'), 'Generated flag set check failed')
  console.log('Imported 248 ISO 4:3 SVG flags from flag-icons v7.3.2.')
}

try {
  main()
} catch (error) {
  console.error(`Flag import failed: ${error.message}`)
  process.exitCode = 1
}
