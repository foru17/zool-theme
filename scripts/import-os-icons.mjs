#!/usr/bin/env node
import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const version = '16.31.0'
const license = 'CC0-1.0'
const slugs = [
  'debian', 'ubuntu', 'centos', 'rockylinux', 'almalinux', 'fedora',
  'redhat', 'archlinux', 'alpinelinux', 'opensuse', 'gentoo', 'nixos',
  'manjaro', 'linuxmint', 'kalilinux', 'raspberrypi', 'openwrt', 'synology',
  'unraid', 'truenas', 'proxmox', 'freebsd', 'openbsd', 'apple', 'android', 'linux',
]
// Source: src/core/glyphs.ts, GLYPHS.windows. Project-drawn generic four-pane
// geometry, not the Microsoft logo; Windows is no longer in simple-icons.
const windowsPath = 'M3 5.4 10.5 4.3v7.2H3zm8.7-1.3L21 2.8v8.7h-9.3zM3 12.5h7.5v7.2L3 18.6zm8.7 0H21v8.7l-9.3-1.3z'
// Windows' tile colour is the familiar Windows blue; simple-icons carries no entry to read it from.
const windowsHex = '0078D4'

/** simple-icons' own title → slug rule, for entries that do not carry an explicit slug. */
const titleToSlug = (title) =>
  title
    .toLowerCase()
    .replace(/\+/g, 'plus')
    .replace(/^\./, 'dot-')
    .replace(/\.(?=.)/g, 'dot')
    .replace(/&/g, 'and')
    .normalize('NFD')
    .replace(/[^a-z0-9]/g, '')

const luminance = (hex) => {
  const channel = (i) => {
    const v = parseInt(hex.slice(i, i + 2), 16) / 255
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
  }
  return 0.2126 * channel(0) + 0.7152 * channel(2) + 0.0722 * channel(4)
}

/**
 * The mark on a brand-coloured tile is white when white reaches 3:1 against the tile — the
 * WCAG floor for graphics — and black otherwise, so Ubuntu orange keeps a white mark while
 * Linux yellow and OpenWrt cyan get a black one.
 */
const markOn = (hex) => ((1.05 / (luminance(hex) + 0.05)) >= 3 ? '#FFFFFF' : '#000000')

function main() {
  const source = join(root, 'node_modules', 'simple-icons')
  const metadata = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8'))
  assert.equal(metadata.version, version, 'Expected simple-icons version 16.31.0')
  assert.equal(metadata.license, license, 'Expected simple-icons license CC0-1.0')
  assert.equal(slugs.length, 26, 'Expected exactly 26 source icons')

  // Validate every input before writing any output; missing icons fail the import.
  const paths = new Map(slugs.map((slug) => {
    const svg = readFileSync(join(source, 'icons', `${slug}.svg`), 'utf8')
    const matches = [...svg.matchAll(/<path\b[^>]*\sd="([^"]*)"[^>]*>/g)]
    assert.equal(matches.length, 1, `Expected exactly one path for ${slug}`)
    const d = matches[0][1]
    assert.ok(d.length > 20, `Empty or truncated path for ${slug}`)
    assert.match(d, /^[MmZzLlHhVvCcSsQqTtAaEe0-9+.,\s-]+$/, `Invalid path data for ${slug}`)
    return [slug, d]
  }))
  paths.set('windows', windowsPath)
  const keys = [...paths.keys()].sort()

  const data = JSON.parse(readFileSync(join(source, 'data', 'simple-icons.json'), 'utf8'))
  const entries = Array.isArray(data) ? data : data.icons
  const colors = new Map(slugs.map((slug) => {
    const entry = entries.find((icon) => (icon.slug ?? titleToSlug(icon.title)) === slug)
    assert.ok(entry, `No simple-icons metadata for ${slug}`)
    assert.match(entry.hex, /^[0-9A-F]{6}$/i, `Invalid brand colour for ${slug}`)
    return [slug, entry.hex.toUpperCase()]
  }))
  colors.set('windows', windowsHex)
  assert.equal(keys.length, 27, 'Expected exactly 27 unique icons')

  const sprite = [
    '<svg xmlns="http://www.w3.org/2000/svg">',
    ...keys.map((key) => `<symbol id="${key}" viewBox="0 0 24 24"><path d="${paths.get(key)}"/></symbol>`),
    '</svg>',
    '',
  ].join('\n')
  const licenseText = readFileSync(join(source, 'LICENSE.md'), 'utf8') +
    '\nThe marks are trademarks of their respective owners and are used only to indicate the ' +
    'operating system a node runs; no endorsement is implied. The windows shape is a generic ' +
    'four-pane figure drawn for this project, not the Microsoft logo. Tile colours are the brand ' +
    'colours recorded in simple-icons metadata.\n' +
    '\n图标为各品牌/项目的商标，仅用于指明节点运行的操作系统，不表示背书；windows 图形为本项目自绘通用四窗格图形，并非微软标志；底板颜色取自 simple-icons 登记的品牌色。\n'
  const manifest = [
    '// generated by scripts/import-os-icons.mjs; do not edit manually.',
    'export const OS_KEYS: ReadonlySet<string> = new Set([',
    ...keys.map((key) => `  '${key}',`),
    '])',
    '',
    '/** Brand colour of each mark (simple-icons metadata) and the mark colour that reads on it. */',
    'export const OS_COLORS: Readonly<Record<string, { tile: string; mark: string }>> = {',
    ...keys.map((key) => `  ${key}: { tile: '#${colors.get(key)}', mark: '${markOn(colors.get(key))}' },`),
    '}',
    '',
    'export const OS_SOURCE = {',
    "  package: 'simple-icons',",
    `  version: '${version}',`,
    `  license: '${license}',`,
    '} as const',
    '',
  ].join('\n')

  const destination = join(root, 'public', 'os')
  mkdirSync(destination, { recursive: true })
  writeFileSync(join(destination, 'sprite.svg'), sprite)
  writeFileSync(join(destination, 'LICENSE.txt'), licenseText)
  writeFileSync(join(root, 'src', 'core', 'os.manifest.ts'), manifest)
  console.log(`Imported 27 OS symbols from simple-icons ${version} and the project windows glyph.`)
}

try {
  main()
} catch (error) {
  console.error(`OS icon import failed: ${error.message}`)
  process.exitCode = 1
}
